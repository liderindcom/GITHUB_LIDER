export const obterBloqueioProdutoLoja = (sku: string, lojaId: string): number => {
  if (globalDbCache.bloqueios) {
    const bloq = globalDbCache.bloqueios.find((b) => b.sku === sku && b.lojaId === lojaId);
    return bloq ? bloq.bloqueio : 0;
  }
  return 0;
};

